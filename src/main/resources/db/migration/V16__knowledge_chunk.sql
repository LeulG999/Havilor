-- Flow 20: Havilor's knowledge for retrieval (RAG): playbook steps and closed alerts, each with an embedding.
-- vector(1024) matches the embedding model in application.yml (havilor.embedding.model, voyage-3.5).
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE knowledge_chunk (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type VARCHAR(20)  NOT NULL,
    source_id   BIGINT       NOT NULL,  -- a playbook step id or an alert id; no FK, the source lives in another module
    content     TEXT         NOT NULL,
    embedding   vector(1024) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,

    CONSTRAINT ck_knowledge_chunk_source_type CHECK (source_type IN ('PLAYBOOK_STEP', 'CLOSED_ALERT')),
    CONSTRAINT uk_knowledge_chunk_source UNIQUE (source_type, source_id)  -- each source is indexed once
);

-- Similarity search: nearest neighbours by cosine distance (the <=> operator), using an HNSW index.
CREATE INDEX idx_knowledge_chunk_embedding ON knowledge_chunk USING hnsw (embedding vector_cosine_ops);
