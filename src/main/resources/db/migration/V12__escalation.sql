-- Flow 15: an alert handed to another team (e.g. the email team, legal), and that team's answer.
CREATE TABLE escalation (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id        BIGINT        NOT NULL REFERENCES alert (id) ON DELETE CASCADE,
    team            VARCHAR(100)  NOT NULL,
    reason          VARCHAR(2000) NOT NULL,
    external_status VARCHAR(20)   NOT NULL,
    outcome         VARCHAR(30),  -- null until the other team has answered

    CONSTRAINT ck_escalation_external_status CHECK (external_status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED')),
    CONSTRAINT ck_escalation_outcome CHECK (outcome IN ('CONFIRMED_MALICIOUS', 'NOT_MALICIOUS', 'INCONCLUSIVE'))
);
