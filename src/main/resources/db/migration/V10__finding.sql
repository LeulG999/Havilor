-- Flow 13: what Havilor (AUTOMATIC) or the analyst (MANUAL) found on an alert, with why it matters.
-- alert_id is a plain foreign key: the finding module stores the id, it never loads the alert.
CREATE TABLE finding (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id      BIGINT       NOT NULL REFERENCES alert (id) ON DELETE CASCADE,
    type          VARCHAR(40)  NOT NULL,
    severity      VARCHAR(20)  NOT NULL,
    title         VARCHAR(300) NOT NULL,
    teaching_text TEXT,
    source        VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,

    CONSTRAINT ck_finding_type CHECK (type IN ('SPF_FAIL', 'DKIM_FAIL', 'DMARC_FAIL', 'BAD_LIST_URL',
                                               'MALICIOUS_ATTACHMENT', 'RECIPIENT_CLICKED', 'OTHER')),
    CONSTRAINT ck_finding_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_finding_source CHECK (source IN ('AUTOMATIC', 'MANUAL'))
);
