-- Flow 14: what the analyst did about an alert (block the sender, purge the email, ...), and how it went.
CREATE TABLE action (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id     BIGINT        NOT NULL REFERENCES alert (id) ON DELETE CASCADE,
    type         VARCHAR(30)   NOT NULL,
    result       VARCHAR(20)   NOT NULL,
    note         VARCHAR(2000),
    performed_by BIGINT        NOT NULL REFERENCES app_user (id),
    performed_at TIMESTAMPTZ   NOT NULL,

    CONSTRAINT ck_action_type CHECK (type IN ('BLOCK_SENDER', 'PURGE_EMAIL', 'RESET_PASSWORD', 'BLOCK_URL',
                                              'NOTIFY_USER', 'OTHER')),
    CONSTRAINT ck_action_result CHECK (result IN ('DONE', 'FAILED', 'PENDING'))
);
