-- Flow 8: an alert follows one playbook (the one active for its case type when it arrived) and tracks
-- one step_progress row per step. playbook_version is stored too, so the record says exactly which
-- checklist the analyst worked through.

ALTER TABLE alert
    ADD COLUMN playbook_id      BIGINT REFERENCES playbook (id),
    ADD COLUMN playbook_version INTEGER;
CREATE INDEX idx_alert_playbook_id ON alert (playbook_id);

CREATE TABLE step_progress (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id         BIGINT      NOT NULL REFERENCES alert (id) ON DELETE CASCADE,
    playbook_step_id BIGINT      NOT NULL REFERENCES playbook_step (id),
    status           VARCHAR(20) NOT NULL,
    answer           TEXT,
    completed_at     TIMESTAMPTZ,
    -- One alert never tracks the same step twice. The index behind it starts with alert_id,
    -- so it also serves "progress rows of alert 42" (no separate alert_id index needed).
    CONSTRAINT uk_step_progress_alert_step UNIQUE (alert_id, playbook_step_id),
    CONSTRAINT ck_step_progress_status CHECK (status IN ('PENDING', 'DONE', 'SKIPPED')),
    -- completed_at is set exactly when the step is finished (DONE or SKIPPED).
    CONSTRAINT ck_step_progress_completed CHECK ((status = 'PENDING') = (completed_at IS NULL))
);
CREATE INDEX idx_step_progress_playbook_step_id ON step_progress (playbook_step_id);

-- Backfill: open alerts that already exist get the active playbook for their case type and PENDING steps,
-- exactly as if they had arrived today. Closed alerts are history and stay without a playbook.
UPDATE alert a
SET playbook_id = p.id, playbook_version = p.version
FROM playbook p
WHERE p.case_type = a.case_type AND p.active AND a.status <> 'CLOSED';

INSERT INTO step_progress (alert_id, playbook_step_id, status)
SELECT a.id, s.id, 'PENDING'
FROM alert a
JOIN playbook_step s ON s.playbook_id = a.playbook_id;
