-- Flow 12: users who log in (ERD: app_user, because "user" is a reserved word in PostgreSQL).
-- Emails are stored lower-case, so the unique constraint is case-insensitive in practice.
CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(320) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,  -- BCrypt, never the password itself
    role          VARCHAR(20)  NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,

    CONSTRAINT uk_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_role CHECK (role IN ('ANALYST', 'MANAGER'))
);

-- alert.assignee_id becomes a real user. Until now it held placeholder numbers with no user behind them,
-- so they are cleared before the foreign key is added.
UPDATE alert SET assignee_id = NULL;
ALTER TABLE alert ADD CONSTRAINT fk_alert_assignee FOREIGN KEY (assignee_id) REFERENCES app_user (id);
