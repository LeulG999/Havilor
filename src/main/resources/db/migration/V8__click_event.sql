-- Flow 10: a click is made by one recipient on one URL of the same alert (ERD: click_event).
-- Both foreign keys cascade: deleting the alert deletes its URLs and recipients, and so their clicks.
CREATE TABLE click_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url_id       BIGINT      NOT NULL REFERENCES url (id) ON DELETE CASCADE,
    recipient_id BIGINT      NOT NULL REFERENCES recipient (id) ON DELETE CASCADE,
    clicked_at   TIMESTAMPTZ NOT NULL,
    permitted    BOOLEAN     NOT NULL  -- true: the click went through; false: the email filter blocked it
);
CREATE INDEX idx_click_event_url_id ON click_event (url_id);
CREATE INDEX idx_click_event_recipient_id ON click_event (recipient_id);
