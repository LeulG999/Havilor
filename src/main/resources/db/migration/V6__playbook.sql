-- Flow 7: the playbook module. A playbook is a versioned checklist for one case type; each step teaches
-- the analyst why it matters. Playbooks are reference data: they change only through migrations.
-- A changed playbook is a NEW row with a higher version, so alerts that used version 1 still point at version 1.

CREATE TABLE playbook (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(200) NOT NULL,
    case_type VARCHAR(30)  NOT NULL,
    version   INTEGER      NOT NULL,
    active    BOOLEAN      NOT NULL,
    CONSTRAINT uk_playbook_case_type_version UNIQUE (case_type, version),
    CONSTRAINT ck_playbook_case_type CHECK (case_type IN ('DETECTED_PHISHING', 'USER_REPORTED_EMAIL', 'RELEASE_REQUEST')),
    CONSTRAINT ck_playbook_version CHECK (version >= 1)
);
-- At most ONE active playbook per case type (a partial unique index: only rows WHERE active count).
CREATE UNIQUE INDEX uk_playbook_one_active_per_case_type ON playbook (case_type) WHERE active;

CREATE TABLE playbook_step (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playbook_id    BIGINT       NOT NULL REFERENCES playbook (id),
    order_no       INTEGER      NOT NULL,
    title          VARCHAR(200) NOT NULL,
    why_it_matters TEXT         NOT NULL,
    question       TEXT         NOT NULL,
    answer_options TEXT,        -- options separated by '|', e.g. 'Malicious|Suspicious|Clean'
    applies_when   VARCHAR(200), -- NULL = always; otherwise the condition, in words
    tool_guide     TEXT,
    CONSTRAINT uk_playbook_step_order UNIQUE (playbook_id, order_no),
    CONSTRAINT ck_playbook_step_order CHECK (order_no >= 1)
);
-- The UNIQUE (playbook_id, order_no) constraint creates an index starting with playbook_id,
-- so "steps of playbook 1, in order" is already an index scan. No extra index needed.

