-- Flow 1: the smallest alert that can be saved and read back.
CREATE TABLE alert (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_number VARCHAR(50)  NOT NULL,
    subject       VARCHAR(500) NOT NULL,
    status        VARCHAR(30)  NOT NULL,
    received_at   TIMESTAMPTZ  NOT NULL,

    -- Idempotency: the same source ticket can only become one alert,
    -- even if two requests race past the service check.
    CONSTRAINT uk_alert_ticket_number UNIQUE (ticket_number)
);
