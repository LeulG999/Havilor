-- Flow 5: the email's recipients, URLs and attachments. Each row belongs to exactly one alert
-- (foreign key on the "many" side). ON DELETE CASCADE: deleting an alert deletes its children.
-- PostgreSQL does not index foreign keys automatically, so every alert_id gets its own index:
-- loading "the children of alert 42" is then an index lookup, not a full table scan.

CREATE TABLE recipient (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id BIGINT       NOT NULL REFERENCES alert (id) ON DELETE CASCADE,
    address  VARCHAR(320) NOT NULL,
    delivery VARCHAR(20)  NOT NULL,
    CONSTRAINT ck_recipient_delivery CHECK (delivery IN ('DELIVERED', 'QUARANTINED', 'RELEASED'))
);
CREATE INDEX idx_recipient_alert_id ON recipient (alert_id);

CREATE TABLE url (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id    BIGINT        NOT NULL REFERENCES alert (id) ON DELETE CASCADE,
    address     VARCHAR(2048) NOT NULL,
    domain      VARCHAR(253),
    on_bad_list BOOLEAN       NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_url_alert_id ON url (alert_id);

CREATE TABLE attachment (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id  BIGINT       NOT NULL REFERENCES alert (id) ON DELETE CASCADE,
    file_name VARCHAR(255) NOT NULL,
    file_type VARCHAR(100),
    sha256    VARCHAR(64),
    verdict   VARCHAR(30),
    CONSTRAINT ck_attachment_verdict CHECK (verdict IN ('UNDECIDED', 'MALICIOUS', 'BENIGN', 'FALSE_POSITIVE'))
);
CREATE INDEX idx_attachment_alert_id ON attachment (alert_id);
