-- Flow 17: an analyst's standup notes for a day, mentioning alerts (many-to-many through standup_note_alert).
CREATE TABLE standup_note (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id BIGINT        NOT NULL REFERENCES app_user (id),
    note_date DATE          NOT NULL,
    text      VARCHAR(10000) NOT NULL,
    status    VARCHAR(20)   NOT NULL,

    CONSTRAINT ck_standup_note_status CHECK (status IN ('DRAFT', 'SHARED'))
);

CREATE TABLE standup_note_alert (
    note_id  BIGINT NOT NULL REFERENCES standup_note (id) ON DELETE CASCADE,
    alert_id BIGINT NOT NULL REFERENCES alert (id) ON DELETE CASCADE,
    PRIMARY KEY (note_id, alert_id)
);
