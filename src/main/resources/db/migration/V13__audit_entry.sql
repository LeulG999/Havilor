-- Flow 16: who changed what, when. Append-only: rows are inserted, never updated or deleted.
-- entity_id has no foreign key on purpose: the log must outlive what it describes.
CREATE TABLE audit_entry (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT      NOT NULL REFERENCES app_user (id),
    action      VARCHAR(50) NOT NULL,
    entity_type VARCHAR(30) NOT NULL,
    entity_id   BIGINT      NOT NULL,
    old_value   TEXT,
    new_value   TEXT,
    created_at  TIMESTAMPTZ NOT NULL
);

-- The database itself refuses to change history, whatever the application does.
CREATE FUNCTION audit_entry_is_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_entry is append-only: % is not allowed', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER audit_entry_no_update_or_delete
    BEFORE UPDATE OR DELETE ON audit_entry
    FOR EACH ROW EXECUTE FUNCTION audit_entry_is_append_only();
